"""Run every saved check and write RESULTS.md.

    python verify_run.py [VERIFY_DIR] [--only PATTERN] [--timeout SECONDS]
                         [--snapshot RUN_DIR]

Each script in VERIFY_DIR/checks prints one line:

    VERDICT: <Lean-PROVED|VERIFIED|VERIFIED-NUMERICALLY|FAILED|UNCHECKED> <id> | <detail>

Lean-PROVED is Sanity's strongest verdict. FAILED, a missing verdict, or more
than one verdict exits 1. UNCHECKED does not. No model is called.
"""

from __future__ import annotations

import datetime
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

from rule import decide

VERDICTS = (
    "Lean-PROVED",
    "VERIFIED",
    "VERIFIED-NUMERICALLY",
    "FAILED",
    "UNCHECKED",
    "ERROR",
)
VERDICT_LINE = re.compile(
    r"^VERDICT:\s*(Lean-PROVED|VERIFIED-NUMERICALLY|VERIFIED|FAILED|UNCHECKED)"
    r"\s+(\S+)\s*\|?\s*(.*)$",
    re.M,
)
FAILURES = {"FAILED", "ERROR"}


def parse_verdict(text: str):
    found = VERDICT_LINE.findall(text)
    if len(found) != 1:
        return None
    name, check_id, detail = found[0]
    return name, check_id, detail.strip()


def project_commit(root: Path) -> str:
    try:
        commit = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=False,
        ).stdout.strip() or "?"
        dirty = subprocess.run(
            ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"],
            capture_output=True,
            text=True,
            check=False,
        ).stdout.strip()
    except OSError:
        return "?"
    if dirty:
        commit += " (+ uncommitted changes)"
    return commit


def check_scripts(verify_dir: Path, only: str) -> list[Path]:
    checks = verify_dir / "checks"
    scripts = sorted(checks.glob("*.py"))
    return [script for script in scripts if only in script.name]


def run_one(script: Path, root: Path, timeout: int) -> tuple[str, str, str, str]:
    env = os.environ.copy()
    env["PYTHONPATH"] = str(root) + os.pathsep + env.get("PYTHONPATH", "")
    started = datetime.datetime.now()
    try:
        completed = subprocess.run(
            [sys.executable, str(script)],
            cwd=root,
            capture_output=True,
            text=True,
            timeout=timeout,
            env=env,
            check=False,
        )
        output = completed.stdout + completed.stderr
        code = completed.returncode
    except subprocess.TimeoutExpired:
        output, code = "", 124
    elapsed = (datetime.datetime.now() - started).total_seconds()
    parsed = parse_verdict(output)
    if parsed is None:
        detail = "timed out" if code == 124 else f"no single VERDICT line, exit {code}"
        if output.strip() and code != 124:
            detail += ": " + output.strip().splitlines()[-1][:150]
        return "ERROR", script.name, detail, f"{elapsed:.1f}s"
    name, check_id, detail = parsed
    return name, check_id, detail.replace("|", "/"), f"{elapsed:.1f}s"


def write_results(verify_dir: Path, rows: list[tuple], commit: str) -> Path:
    counts = {name: sum(row[1] == name for row in rows) for name in VERDICTS}
    lines = [
        "# Verification results (generated by verify_run; do not edit)",
        "",
        f"Run: {datetime.datetime.now():%Y-%m-%d %H:%M}. Project commit: {commit}.",
        "",
        " · ".join(f"{name}: {counts[name]}" for name in VERDICTS),
        "",
        "| check | verdict | engine | time | script | detail |",
        "|---|---|---|---|---|---|",
    ]
    for check_id, name, engine, timing, script, detail in rows:
        lines.append(
            f"| {check_id} | **{name}** | {engine} | {timing} | `checks/{script}` | {detail} |"
        )
    lines.extend(
        [
            "",
            "## Rulings",
            "",
            "The Verifier confirms or rejects each row from the verdict column only.",
            "Lean-verified is set only when the verdict is Lean-PROVED.",
            "",
            "| check | verdict | ruling | lean-verified |",
            "|---|---|---|---|",
        ]
    )
    for check_id, name, _engine, _timing, _script, _detail in rows:
        ruling = decide(name)
        lean = "yes" if ruling.lean_verified else "no"
        lines.append(f"| {check_id} | {name} | {ruling.decision} | {lean} |")
    lines.append("")
    destination = verify_dir / "RESULTS.md"
    destination.write_text("\n".join(lines), encoding="utf-8")
    return destination


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    options = {"--only": "", "--timeout": "120", "--snapshot": ""}
    positionals = []
    index = 0
    while index < len(args):
        arg = args[index]
        if arg in options:
            if index + 1 >= len(args):
                print(f"verify_run: {arg} needs a value", file=sys.stderr)
                return 2
            options[arg] = args[index + 1]
            index += 2
            continue
        if arg.startswith("--"):
            print(f"verify_run: unknown option {arg}", file=sys.stderr)
            return 2
        positionals.append(arg)
        index += 1
    default = Path(__file__).resolve().parent / "verify"
    verify_dir = Path(positionals[0]).resolve() if positionals else default
    scripts = check_scripts(verify_dir, options["--only"])
    if not scripts:
        print(f"verify_run: no checks in {verify_dir / 'checks'}", file=sys.stderr)
        return 2
    root = verify_dir.parent
    timeout = int(options["--timeout"])
    rows = []
    failed = 0
    for script in scripts:
        name, check_id, detail, timing = run_one(script, root, timeout)
        if name in FAILURES:
            failed += 1
        rows.append((check_id, name, "SymPy/Python", timing, script.name, detail))
        print(f"{name:22} {check_id:32} {timing:>6}  {detail[:90]}")
    results = write_results(verify_dir, rows, project_commit(root))
    snapshot = options["--snapshot"]
    if snapshot:
        folder = Path(snapshot)
        folder.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(results, folder / "RESULTS.md")
    print(f"\n{ {name: sum(row[1] == name for row in rows) for name in VERDICTS} }  ->  {results}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
